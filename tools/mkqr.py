#!/usr/bin/env python3
"""Pre-generate the credits QR code (see PLAN.md "Credits & QR").

Emits src/gfx/qr.c/qr.h:
  qr_tiles  - 4bpp GBA tiles at 4px/module (dark=1, light=2), row-major,
              QR_TILE_W x QR_TILE_W tiles for the credits screen
  qr_page   - 5,760-byte GB 2bpp printed page, QR centered (dark=color 3)
Plus .scratchwork/qr_preview.png for inspection.
"""
import os, re, struct, zlib
import segno
from mklogo import logo_grid

URL = "https://scottratchford.com"
URL_SHORT = "scottratchford.com"   # printed under the code (fits 20 chars/row)
SCALE = 4          # pixels per module

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def parse_font8x8(path, array_name):   # same format as mkfont.py
    src = open(path).read()
    m = re.search(array_name + r"\[\d+\]\[8\]\s*=\s*\{(.*?)\};", src, re.S)
    glyphs = []
    for gm in re.finditer(r"\{([^}]*)\}", m.group(1)):
        glyphs.append([int(x, 16) for x in re.findall(r"0x[0-9A-Fa-f]{2}", gm.group(1))])
    return glyphs

FONT = parse_font8x8(os.path.join(ROOT, "tools/font8x8/font8x8_basic.h"), "font8x8_basic")

qr = segno.make(URL, error='m', micro=False)
matrix = [list(row) for row in qr.matrix]
n = len(matrix)
print(f"QR version {qr.version}, {n}x{n} modules")

px_size = n * SCALE                     # e.g. 25*4 = 100
tile_w = (px_size + 7) // 8             # tiles per side (13 for 100px)

def module_at(px, py):
    """dark? for pixel coords inside the code area"""
    mx, my = px // SCALE, py // SCALE
    if 0 <= mx < n and 0 <= my < n:
        return matrix[my][mx]
    return 0

# ---- screen tiles: 4bpp, dark=1 light=2 (palette bank supplies black/white)
words = []
for ty in range(tile_w):
    for tx in range(tile_w):
        for y in range(8):
            w = 0
            for x in range(8):
                px, py = tx * 8 + x, ty * 8 + y
                if px < px_size and py < px_size:
                    v = 1 if module_at(px, py) else 2
                else:
                    v = 2                       # pad stays light
                w |= v << (4 * x)
            words.append(w)

# ---- print page: 160x144 GB 2bpp — logo on top, QR centered, URL below
PAGE_W, PAGE_H, TILES_PER_ROW = 160, 144, 20
page = bytearray(5760)

def put_px(px_, py, shade):
    """set one pixel to GB shade 0..3 (0 = white paper)"""
    ti = (py // 8) * TILES_PER_ROW + px_ // 8
    off = ti * 16 + (py % 8) * 2
    bit = 0x80 >> (px_ % 8)
    if shade & 1: page[off]     |= bit
    if shade & 2: page[off + 1] |= bit

# logo: 16x16 top center; sketch shades ARE print shades (0=white .. 3=black)
LOGO_SHADE = {0: 0, 1: 1, 2: 2, 3: 3}
lg = logo_grid()
lx, ly = (PAGE_W - 16) // 2, 2
for y in range(16):
    for x in range(16):
        s = LOGO_SHADE[lg[y][x]]
        if s:
            put_px(lx + x, ly + y, s)

# QR: centered horizontally, below the logo
ox, oy = (PAGE_W - px_size) // 2, 22
for py in range(px_size):
    for px_ in range(px_size):
        if module_at(px_, py):
            put_px(ox + px_, oy + py, 3)

# URL text: 8x8 glyphs, centered, below the QR
tx0, ty0 = (PAGE_W - len(URL_SHORT) * 8) // 2, oy + px_size + 6
for ci, ch in enumerate(URL_SHORT):
    rows = FONT[ord(ch)]
    for y in range(8):
        for x in range(8):
            if (rows[y] >> x) & 1:          # LSB = leftmost
                put_px(tx0 + ci * 8 + x, ty0 + y, 3)

with open(os.path.join(ROOT, "src/gfx/qr.c"), "w") as f:
    f.write("// Generated by tools/mkqr.py - do not edit\n#include \"qr.h\"\n\n")
    f.write("const unsigned int qr_tiles[%d] = {\n" % len(words))
    for i in range(0, len(words), 8):
        f.write("    " + ",".join("0x%08X" % w for w in words[i:i+8]) + ",\n")
    f.write("};\n\nconst unsigned char qr_page[5760] = {\n")
    for i in range(0, 5760, 16):
        f.write("    " + ",".join("0x%02X" % b for b in page[i:i+16]) + ",\n")
    f.write("};\n")

with open(os.path.join(ROOT, "src/gfx/qr.h"), "w") as f:
    f.write("""// Generated by tools/mkqr.py - do not edit
#ifndef GFX_QR_H
#define GFX_QR_H
#define QR_TILE_W %d
#define QR_URL "%s"
extern const unsigned int qr_tiles[%d];
extern const unsigned char qr_page[5760];
#endif
""" % (tile_w, URL, len(words)))

# ---- preview PNG (print page rendering, 2x)
S = 2
W, H = PAGE_W * S, PAGE_H * S
gray = bytearray(b"\xff" * (W * H))
for py in range(PAGE_H):
    for px_ in range(PAGE_W):
        ti = (py // 8) * TILES_PER_ROW + px_ // 8
        off = ti * 16 + (py % 8) * 2
        bit = 0x80 >> (px_ % 8)
        if page[off] & bit:
            for sy in range(S):
                for sx in range(S):
                    gray[(py * S + sy) * W + px_ * S + sx] = 0

def chunk(t, d):
    c = t + d
    return struct.pack(">I", len(d)) + c + struct.pack(">I", zlib.crc32(c))
raw = b"".join(b"\x00" + bytes(gray[y * W:(y + 1) * W]) for y in range(H))
png = (b"\x89PNG\r\n\x1a\n"
       + chunk(b"IHDR", struct.pack(">IIBBBBB", W, H, 8, 0, 0, 0, 0))
       + chunk(b"IDAT", zlib.compress(raw)) + chunk(b"IEND", b""))
os.makedirs(os.path.join(ROOT, ".scratchwork"), exist_ok=True)
open(os.path.join(ROOT, ".scratchwork/qr_preview.png"), "wb").write(png)
print("qr.c/qr.h + preview written")
