#!/usr/bin/env python3
"""GBScribe logo: 16x16 pixel Game Boy with quill + ink pot (user sketch).

Emits:
  src/gfx/logo.c/h        - logo_tiles: 4bpp GBA tiles, 2x2 tiles, values
                            1=outline/quill/ink, 2=body, 3=screen
  assets/logo.png         - x8 colored render (committed, used by README.md)
  .scratchwork/logo_preview.png - x16 render for visual inspection

mkqr.py imports logo_grid() to stamp the logo onto the printed QR page.
"""
import os, struct, zlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# '.'=transparent  '#'=outline/quill/ink  'b'=body fill  's'=screen
ART = [
    ".............##.",
    "...........####.",
    "#########.###...",
    "#sssssss###.....",
    "#ssssss##.......",
    "#sssss#s#.......",
    "#sss##ss#.......",
    "#########.......",
    "#bbbbbbb#.......",
    "#b#bbb#b#.......",
    "####b#bb#...##..",
    "#b#bbbbb#..####.",
    "#bbbbbbb#.######",
    "#bbbb#b##.#s####",
    "#bbbbbbb#.######",
    "#########..####.",
]
VAL = {'.': 0, '#': 1, 'b': 2, 's': 3}

def logo_grid():
    """16x16 grid of palette values 0..3"""
    return [[VAL[c] for c in row] for row in ART]

def write_png_rgba(path, w, h, rgba):
    def chunk(t, d):
        c = t + d
        return struct.pack(">I", len(d)) + c + struct.pack(">I", zlib.crc32(c))
    raw = b"".join(b"\x00" + bytes(rgba[y * w * 4:(y + 1) * w * 4]) for y in range(h))
    png = (b"\x89PNG\r\n\x1a\n"
           + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0))
           + chunk(b"IDAT", zlib.compress(raw)) + chunk(b"IEND", b""))
    open(path, "wb").write(png)

def render(scale, colors, bg):
    g = logo_grid()
    w = h = 16 * scale
    buf = bytearray(w * h * 4)
    for y in range(h):
        for x in range(w):
            v = g[y // scale][x // scale]
            r, gg, b, a = colors[v] if v else bg
            i = (y * w + x) * 4
            buf[i:i+4] = bytes((r, gg, b, a))
    return w, h, buf

if __name__ == "__main__":
    # title-screen look: light outline, gray body, GB-green screen on dark
    colors = {1: (232, 234, 246, 255), 2: (110, 120, 150, 255), 3: (155, 188, 15, 255)}
    dark_bg = (34, 40, 58, 255)

    os.makedirs(os.path.join(ROOT, "assets"), exist_ok=True)
    w, h, buf = render(8, colors, dark_bg)
    write_png_rgba(os.path.join(ROOT, "assets/logo.png"), w, h, buf)
    os.makedirs(os.path.join(ROOT, ".scratchwork"), exist_ok=True)
    w, h, buf = render(16, colors, dark_bg)
    write_png_rgba(os.path.join(ROOT, ".scratchwork/logo_preview.png"), w, h, buf)

    # 4bpp tiles: 2x2 tiles, row-major, pixel value = palette index 0..3
    g = logo_grid()
    words = []
    for ty in range(2):
        for tx in range(2):
            for y in range(8):
                wd = 0
                for x in range(8):
                    wd |= g[ty * 8 + y][tx * 8 + x] << (4 * x)
                words.append(wd)

    with open(os.path.join(ROOT, "src/gfx/logo.c"), "w") as f:
        f.write("// Generated by tools/mklogo.py - do not edit\n#include \"logo.h\"\n\n")
        f.write("const unsigned int logo_tiles[%d] = {\n" % len(words))
        for i in range(0, len(words), 8):
            f.write("    " + ",".join("0x%08X" % wd for wd in words[i:i+8]) + ",\n")
        f.write("};\n")
    with open(os.path.join(ROOT, "src/gfx/logo.h"), "w") as f:
        f.write("""// Generated by tools/mklogo.py - do not edit
// 16x16 logo, 2x2 4bpp tiles. Palette values: 1=outline/quill/ink (light),
// 2=body (gray), 3=screen (green).
#ifndef GFX_LOGO_H
#define GFX_LOGO_H
#define LOGO_TILE_W 2
extern const unsigned int logo_tiles[%d];
#endif
""" % len(words))
    print("logo.c/h + assets/logo.png + preview written")
