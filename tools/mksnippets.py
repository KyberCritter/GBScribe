#!/usr/bin/env python3
"""Pre-generate the secret debug menu's book snippets from temp/*.txt.

Each temp/<Name>.txt becomes a menu entry called <Name> (the option label on
the debug menu reached via the Konami code on the title screen). Text is
sanitized to the GBScribe charset (ASCII 0x20..0x7E + '\\n'); typographic
quotes/dashes are mapped to ASCII equivalents.

Emits src/core/snippets.c/h. Re-run whenever temp/ changes.
"""
import glob, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

REPLACE = {
    "‘": "'", "’": "'",       # curly single quotes
    "“": '"', "”": '"',       # curly double quotes
    "–": "-", "—": "--",      # en/em dash
    "…": "...",                    # ellipsis
    " ": " ",                      # nbsp
    "\r": "",
    "\t": "  ",
}

def sanitize(text, name):
    for k, v in REPLACE.items():
        text = text.replace(k, v)
    for ch in text:
        if ch != "\n" and not (0x20 <= ord(ch) <= 0x7E):
            raise SystemExit("%s: unmappable char U+%04X" % (name, ord(ch)))
    return text.strip("\n") + "\n"

def c_string_lines(text):
    """one C literal per source line, keeping the output readable"""
    out = []
    for ln in text.split("\n")[:-1]:
        esc = ln.replace("\\", "\\\\").replace('"', '\\"')
        out.append('    "%s\\n"' % esc)
    return "\n".join(out)

files = sorted(glob.glob(os.path.join(ROOT, "temp", "*.txt")))
if not files:
    raise SystemExit("no temp/*.txt snippet files found")

snippets = []
for path in files:
    name = os.path.splitext(os.path.basename(path))[0]
    text = sanitize(open(path, encoding="utf-8").read(), name)
    snippets.append((name, text))
    if len(name) > 20:
        raise SystemExit("name too long for a menu row: " + name)

with open(os.path.join(ROOT, "src/core/snippets.c"), "w") as f:
    f.write("// Generated by tools/mksnippets.py from temp/*.txt - do not edit\n")
    f.write('#include "snippets.h"\n\n')
    for i, (name, text) in enumerate(snippets):
        f.write("static const char text_%d[] =\n%s;\n\n" % (i, c_string_lines(text)))
    f.write("const Snippet snippets[SNIPPET_COUNT] = {\n")
    for i, (name, text) in enumerate(snippets):
        f.write('    { "%s", text_%d, sizeof text_%d - 1 },\n' % (name, i, i))
    f.write("};\n")

with open(os.path.join(ROOT, "src/core/snippets.h"), "w") as f:
    f.write("""// Generated by tools/mksnippets.py from temp/*.txt - do not edit
// Book snippets for the secret debug menu (Konami code on the title screen).
#ifndef CORE_SNIPPETS_H
#define CORE_SNIPPETS_H

#define SNIPPET_COUNT %d

typedef struct {
    const char *name;   // menu label (source filename)
    const char *text;   // charset text, printed via the document print path
    int len;
} Snippet;

extern const Snippet snippets[SNIPPET_COUNT];

#endif
""" % len(snippets))

print("snippets.c/h written: " + ", ".join(n for n, _ in snippets))
