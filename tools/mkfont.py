#!/usr/bin/env python3
"""Generate the GBScribe font from font8x8 (public domain) + hand-authored glyphs.

Outputs:
  src/gfx/font.c / font.h   - 4bpp GBA tiles: 128 font tiles + 8 solid tiles
  src/gfx/font2bpp.c        - GB 2bpp print font (128 x 16 bytes), same glyph order
  .scratchwork/font_preview.png - 16x8 glyph grid, 4x scale, for visual inspection

Charset (internal codes 0x00..0x7F):
  0x00        blank
  0x01..0x04  arrows: up down left right
  0x05..0x09  shapes: fsq hsq fcirc hcirc ftri
  0x0A        NEWLINE control (blank glyph) - keeps '\\n' ASCII-compatible
  0x0B..0x0D  shapes: htri fdia hdia
  0x0E..0x18  box: - | TL TR BL BR |- -| T-down T-up +
  0x19..0x1F  blank
  0x20..0x7E  ASCII
  0x7F        blank
font8x8 format: byte per row, LSB = leftmost pixel.
"""
import os, re, struct, zlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def parse_font8x8(path, array_name):
    src = open(path).read()
    m = re.search(array_name + r"\[\d+\]\[8\]\s*=\s*\{(.*?)\};", src, re.S)
    body = m.group(1)
    glyphs = []
    for gm in re.finditer(r"\{([^}]*)\}", body):
        rows = [int(x, 16) for x in re.findall(r"0x[0-9A-Fa-f]{2}", gm.group(1))]
        assert len(rows) == 8
        glyphs.append(rows)
    return glyphs

basic = parse_font8x8(os.path.join(ROOT, "tools/font8x8/font8x8_basic.h"), "font8x8_basic")
box   = parse_font8x8(os.path.join(ROOT, "tools/font8x8/font8x8_box.h"),   "font8x8_box")

def g(*rows):  # glyph from visual strings: '#'=ink
    return [sum(1 << x for x in range(8) if r[x] == '#') for r in rows]

BLANK = [0]*8
arrows = [
    g("...#....","..###...",".#.#.#..","#..#..#.","...#....","...#....","...#....","........"),  # up
    g("...#....","...#....","...#....","#..#..#.",".#.#.#..","..###...","...#....","........"),  # down
    g("........","..#.....",".#......","#######.",".#......","..#.....","........","........"),  # left
    g("........","....#...",".....#..","#######.",".....#..","....#...","........","........"),  # right
]
shapes = [
    g("........","######..","######..","######..","######..","######..","######..","........"),  # filled sq
    g("........","######..","#....#..","#....#..","#....#..","#....#..","######..","........"),  # hollow sq
    g("........",".####...","######..","######..","######..","######..",".####...","........"),  # filled circ
    g("........",".####...","#....#..","#....#..","#....#..","#....#..",".####...","........"),  # hollow circ
    g("...#....","...#....","..###...","..###...",".#####..",".#####..","#######.","........"),  # filled tri
    g("...#....","...#....","..#.#...","..#.#...",".#...#..",".#...#..","#######.","........"),  # hollow tri
    g("...#....","..###...",".#####..","#######.",".#####..","..###...","...#....","........"),  # filled dia
    g("...#....","..#.#...",".#...#..","#.....#.",".#...#..","..#.#...","...#....","........"),  # hollow dia
]
# box glyph indices in font8x8_box (U+2500 block): ─ │ ┌ ┐ └ ┘ ├ ┤ ┬ ┴ ┼
box_codes = [0x00, 0x02, 0x0C, 0x10, 0x14, 0x18, 0x1C, 0x24, 0x2C, 0x34, 0x3C]

charset = [BLANK]  # 0x00
charset += arrows                          # 0x01-0x04
charset += shapes[:5]                      # 0x05-0x09
charset += [BLANK]                         # 0x0A NEWLINE
charset += shapes[5:]                      # 0x0B-0x0D
charset += [box[i] for i in box_codes]     # 0x0E-0x18
charset += [BLANK] * 7                     # 0x19-0x1F
charset += [basic[c] for c in range(0x20, 0x7F)]  # 0x20-0x7E
charset += [BLANK]                         # 0x7F
assert len(charset) == 128

# ---- 4bpp GBA tiles (ink = pixel value 1) + 8 solid tiles (values 1..8)
def tile4bpp(rows, val=1):
    words = []
    for r in rows:
        w = 0
        for x in range(8):
            if (r >> x) & 1:
                w |= val << (4 * x)
        words.append(w)
    return words

words = []
for rows in charset:
    words += tile4bpp(rows)
for v in range(1, 9):  # solid tiles 128..135, filled with palette index v
    words += tile4bpp([0xFF]*8, v)

with open(os.path.join(ROOT, "src/gfx/font.c"), "w") as f:
    f.write("// Generated by tools/mkfont.py - do not edit\n#include \"font.h\"\n\n")
    f.write("const unsigned int font_tiles[%d] = {\n" % len(words))
    for i in range(0, len(words), 8):
        f.write("    " + ",".join("0x%08X" % w for w in words[i:i+8]) + ",\n")
    f.write("};\n")

with open(os.path.join(ROOT, "src/gfx/font.h"), "w") as f:
    f.write("""// Generated by tools/mkfont.py - do not edit
#ifndef GFX_FONT_H
#define GFX_FONT_H
#define FONT_TILE_COUNT 136
#define FONT_SOLID_TILE(v) (128 + (v) - 1)  // solid tile filled with palette index v (1..8)
extern const unsigned int font_tiles[FONT_TILE_COUNT * 8];
#endif
""")

# ---- GB 2bpp print font: ink = color 3 (both bitplanes set)
data = bytearray()
for rows in charset:
    for r in rows:
        b = 0
        for x in range(8):           # GB: MSB = leftmost pixel
            if (r >> x) & 1:
                b |= 0x80 >> x
        data.append(b)  # plane 0
        data.append(b)  # plane 1  (color 3 = black)
with open(os.path.join(ROOT, "src/gfx/font2bpp.c"), "w") as f:
    f.write("// Generated by tools/mkfont.py - do not edit\n")
    f.write("// GB 2bpp print font, 128 glyphs x 16 bytes, same codes as screen font\n")
    f.write("const unsigned char font2bpp[%d] = {\n" % len(data))
    for i in range(0, len(data), 16):
        f.write("    " + ",".join("0x%02X" % b for b in data[i:i+16]) + ",\n")
    f.write("};\n")

# ---- preview PNG (16x8 grid, 4x scale)
SCALE, COLS, GRID_ROWS = 4, 16, 8
W, H = COLS*8*SCALE, GRID_ROWS*8*SCALE
px = bytearray(W*H)  # grayscale, 0 = black
for idx, rows in enumerate(charset):
    gx, gy = (idx % COLS)*8, (idx // COLS)*8
    for y in range(8):
        for x in range(8):
            on = (rows[y] >> x) & 1
            for sy in range(SCALE):
                for sx in range(SCALE):
                    px[((gy+y)*SCALE+sy)*W + (gx+x)*SCALE+sx] = 255 if on else 40 + 15*(((idx % COLS)//1 + idx//COLS) % 2)

def write_png(path, w, h, gray):
    raw = b"".join(b"\x00" + bytes(gray[y*w:(y+1)*w]) for y in range(h))
    def chunk(t, d):
        c = t + d
        return struct.pack(">I", len(d)) + c + struct.pack(">I", zlib.crc32(c))
    png = b"\x89PNG\r\n\x1a\n"
    png += chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 0, 0, 0, 0))
    png += chunk(b"IDAT", zlib.compress(raw))
    png += chunk(b"IEND", b"")
    open(path, "wb").write(png)

os.makedirs(os.path.join(ROOT, ".scratchwork"), exist_ok=True)
write_png(os.path.join(ROOT, ".scratchwork/font_preview.png"), W, H, px)
print("font.c/font.h/font2bpp.c + preview written")
