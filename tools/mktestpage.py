#!/usr/bin/env python3
"""Pre-generate the printer test page (title chooser: "Print test page").

Emits src/gfx/testpage.c/h:
  testpage_page - 5,760-byte GB 2bpp page: border, logo, title text, the four
                  print shades as labeled bands, alignment patterns, footer
Plus .scratchwork/testpage_preview.png for inspection.
"""
import os, re, struct, zlib
from mklogo import logo_grid

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def parse_font8x8(path, array_name):   # same format as mkfont.py
    src = open(path).read()
    m = re.search(array_name + r"\[\d+\]\[8\]\s*=\s*\{(.*?)\};", src, re.S)
    glyphs = []
    for gm in re.finditer(r"\{([^}]*)\}", m.group(1)):
        glyphs.append([int(x, 16) for x in re.findall(r"0x[0-9A-Fa-f]{2}", gm.group(1))])
    return glyphs

FONT = parse_font8x8(os.path.join(ROOT, "tools/font8x8/font8x8_basic.h"), "font8x8_basic")

PAGE_W, PAGE_H, TILES_PER_ROW = 160, 144, 20
page = bytearray(5760)

def put_px(px, py, shade):
    """set one pixel to GB shade 0..3 (0 = white paper)"""
    ti = (py // 8) * TILES_PER_ROW + px // 8
    off = ti * 16 + (py % 8) * 2
    bit = 0x80 >> (px % 8)
    if shade & 1: page[off]     |= bit
    if shade & 2: page[off + 1] |= bit

def rect(x, y, w, h, shade):
    for yy in range(y, y + h):
        for xx in range(x, x + w):
            put_px(xx, yy, shade)

def outline(x, y, w, h, shade):
    for xx in range(x, x + w):
        put_px(xx, y, shade); put_px(xx, y + h - 1, shade)
    for yy in range(y, y + h):
        put_px(x, yy, shade); put_px(x + w - 1, yy, shade)

def text(s, y, shade=3):
    x0 = (PAGE_W - len(s) * 8) // 2
    for ci, ch in enumerate(s):
        rows = FONT[ord(ch)]
        for yy in range(8):
            for xx in range(8):
                if (rows[yy] >> xx) & 1:        # LSB = leftmost
                    put_px(x0 + ci * 8 + xx, y + yy, shade)

# 1px page border
outline(0, 0, PAGE_W, PAGE_H, 3)

# logo top center; sketch shades ARE print shades
lg = logo_grid()
lx = (PAGE_W - 16) // 2
for y in range(16):
    for x in range(16):
        if lg[y][x]:
            put_px(lx + x, 6 + y, lg[y][x])

text("GBSCRIBE", 26)
text("TEST PAGE", 36)

# the four print shades: labeled 28px bands, outlined so shade 0 shows
bx0 = (PAGE_W - 4 * 32) // 2
for i in range(4):
    x = bx0 + i * 32
    rect(x, 52, 28, 20, i)
    outline(x, 52, 28, 20, 3)
    ch = FONT[ord('0') + i]
    for yy in range(8):
        for xx in range(8):
            if (ch[yy] >> xx) & 1:
                put_px(x + 10 + xx, 75 + yy, 3)

# alignment: 1px checker, 2px checker, 4px vertical stripes
for y in range(90, 98):
    for x in range(8, PAGE_W - 8):
        if (x + y) & 1:
            put_px(x, y, 3)
for y in range(101, 109):
    for x in range(8, PAGE_W - 8):
        if ((x >> 1) + (y >> 1)) & 1:
            put_px(x, y, 3)
for y in range(112, 120):
    for x in range(8, PAGE_W - 8):
        if (x >> 2) & 1:
            put_px(x, y, 3)

text("IF YOU CAN READ", 126)
text("THIS, IT WORKS!", 135)

with open(os.path.join(ROOT, "src/gfx/testpage.c"), "w") as f:
    f.write("// Generated by tools/mktestpage.py - do not edit\n#include \"testpage.h\"\n\n")
    f.write("const unsigned char testpage_page[5760] = {\n")
    for i in range(0, 5760, 16):
        f.write("    " + ",".join("0x%02X" % b for b in page[i:i+16]) + ",\n")
    f.write("};\n")

with open(os.path.join(ROOT, "src/gfx/testpage.h"), "w") as f:
    f.write("""// Generated by tools/mktestpage.py - do not edit
#ifndef GFX_TESTPAGE_H
#define GFX_TESTPAGE_H
extern const unsigned char testpage_page[5760];
#endif
""")

# preview PNG (grayscale, 2x) using all 4 shades
S = 2
W, H = PAGE_W * S, PAGE_H * S
SHADE_GRAY = [0xFF, 0xAA, 0x55, 0x00]
gray = bytearray(b"\xff" * (W * H))
for py in range(PAGE_H):
    for px in range(PAGE_W):
        ti = (py // 8) * TILES_PER_ROW + px // 8
        off = ti * 16 + (py % 8) * 2
        bit = 0x80 >> (px % 8)
        s = (1 if page[off] & bit else 0) | (2 if page[off + 1] & bit else 0)
        if s:
            for sy in range(S):
                for sx in range(S):
                    gray[(py * S + sy) * W + px * S + sx] = SHADE_GRAY[s]

def chunk(t, d):
    c = t + d
    return struct.pack(">I", len(d)) + c + struct.pack(">I", zlib.crc32(c))
raw = b"".join(b"\x00" + bytes(gray[y * W:(y + 1) * W]) for y in range(H))
png = (b"\x89PNG\r\n\x1a\n"
       + chunk(b"IHDR", struct.pack(">IIBBBBB", W, H, 8, 0, 0, 0, 0))
       + chunk(b"IDAT", zlib.compress(raw)) + chunk(b"IEND", b""))
os.makedirs(os.path.join(ROOT, ".scratchwork"), exist_ok=True)
open(os.path.join(ROOT, ".scratchwork/testpage_preview.png"), "wb").write(png)
print("testpage.c/h + preview written")
